"""
main.py
========

This module serves as the central orchestrator for the 'Autonomous Architect CLI' application.
It enables interaction with various LLM providers (e.g., Google Gemini, OpenAI) to execute user tasks,
manage conversational sessions, dynamically load and execute 'skills' (tools), and facilitate the
generation of new skill manifests. The application supports two primary modes: a command-line interface
(`run-task`, `generate-skill`) and an interactive chat loop for continuous interaction.

Key Responsibilities:
--------------------
- **Task Execution**: Drives the core conversational loop with the selected LLM for user task execution.
- **Skill Management**: Handles dynamic loading and integration of external tools/skills.
- **Session Management**: Maintains conversational context and state across interactions.
- **Error Handling & Logging**: Provides robust error handling and structured logging for operational stability.
- **Skill Generation**: Facilitates the creation of new skill manifests.
- **CLI Interface**: Exposes functionality via a command-line interface.

Components & Interactions:
--------------------------
- `ChesterRequest`/`ChesterResponse`: Data models for structured communication with the LLM.
- `Session`/`Model`: Manages session state and LLM model configuration.
- `architect`/`skill_creator` agents: Logic for generating system prompts and new skill manifests.
- `Skill`: Abstraction for managing and loading available tools.
- `argparse`: CLI parsing for `run-task` and `generate-skill` commands.
- `LLMClient` (new abstraction): Provides a uniform interface for different LLM providers.

"""
